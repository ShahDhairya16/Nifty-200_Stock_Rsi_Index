import pandas as pd
import streamlit as st


def normalize_confidence(value) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0.0
    if 0.0 <= number <= 1.0:
        number *= 100.0
    return max(0.0, min(100.0, number))


def recommendation_frame(result) -> pd.DataFrame:
    recommendations = (result or {}).get("recommendations") or []
    table = pd.DataFrame(recommendations)
    if table.empty:
        return table
    if "confidence" in table.columns:
        table["confidence"] = table["confidence"].map(normalize_confidence)
    if "allocation_percent" in table.columns:
        table["allocation_percent"] = pd.to_numeric(
            table["allocation_percent"], errors="coerce"
        ).fillna(0).clip(0, 100)
    return table


def render_ai_recommendations(result, limit: int = 5, show_summary: bool = True) -> None:
    if result is None:
        return
    error = result.get("error")
    if error:
        if error == "missing_key":
            st.caption("Add GEMINI_API_KEY to enable automatic AI suggestions.")
        else:
            st.caption(f"AI suggestions are temporarily unavailable: {error}")
        return

    if show_summary and result.get("summary"):
        st.markdown(str(result["summary"]))

    table = recommendation_frame(result)
    if table.empty:
        st.caption("Gemini did not return a structured list for this request.")
        return

    preferred = [
        "symbol",
        "company_name",
        "action",
        "confidence",
        "allocation_percent",
        "rationale",
        "risks",
    ]
    available = [column for column in preferred if column in table.columns]
    view = table[available].head(limit).rename(
        columns={
            "symbol": "Symbol",
            "company_name": "Company",
            "action": "Action",
            "confidence": "Confidence",
            "allocation_percent": "Allocation %",
            "rationale": "Why",
            "risks": "Main risk",
        }
    )
    st.dataframe(
        view,
        hide_index=True,
        width="stretch",
        column_config={
            "Confidence": st.column_config.ProgressColumn(
                "Confidence", min_value=0, max_value=100, format="%d"
            ),
            "Allocation %": st.column_config.NumberColumn(format="%.1f%%"),
            "Why": st.column_config.TextColumn(width="large"),
            "Main risk": st.column_config.TextColumn(width="large"),
        },
    )
    st.caption(
        "Auto-generated by Gemini from the latest RSI snapshot. "
        "Educational only — verify independently before investing."
    )
